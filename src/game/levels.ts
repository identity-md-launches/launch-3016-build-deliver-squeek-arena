import type { Collectible, Enemy, EnemyKind, Level, Platform } from "./types";

const ground = (segments: [number, number][]): Platform[] =>
  segments.map(([x, w]) => ({ x, y: 408, w, h: 160 }));
const ledge = (x: number, y: number, w: number): Platform => ({
  x,
  y,
  w,
  h: 18,
});
const enemy = (
  id: number,
  kind: EnemyKind,
  x: number,
  y = 378,
  range = 100,
): Enemy => ({
  id,
  kind,
  x,
  y,
  w: kind === "moth" ? 30 : 34,
  h: kind === "moth" ? 26 : 30,
  hp: kind === "sentry" ? 3 : 2,
  maxHp: kind === "sentry" ? 3 : 2,
  home: x,
  range,
  vx: kind === "beetle" ? 38 : 0,
  vy: 0,
  time: id * 0.7,
  state: "patrol",
  timer: 0,
  hit: 0,
  lastAttack: -1,
  dead: false,
});
const seeds = (prefix: string, points: [number, number][]): Collectible[] =>
  points.map(([x, y], i) => ({
    id: `${prefix}-${i}`,
    x,
    y,
    w: 16,
    h: 18,
    kind: "seed",
    taken: false,
  }));
const row = (x: number, y: number, n: number): [number, number][] =>
  Array.from({ length: n }, (_, i) => [x + i * 34, y]);
const relic = (id: string, x: number, y: number): Collectible => ({
  id,
  x,
  y,
  w: 20,
  h: 24,
  kind: "relic",
  taken: false,
});
const heart = (id: string, x: number, y = 374): Collectible => ({
  id,
  x,
  y,
  w: 20,
  h: 18,
  kind: "heart",
  taken: false,
});

